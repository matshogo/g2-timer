import type { Pattern } from '../types'
import { pattern } from './util'

// 基本単語モジュール: 単語そのものをカード化する(korean = chunk = 単語)。

function words(course: 'vocab', id: string, title: string, category: string, pairs: [string, string][]): Pattern {
  return pattern(
    course,
    id,
    title,
    '',
    category,
    pairs.map(([ko, ja]) => [ko, ja, ko, ja] as [string, string, string, string]),
  )
}

