import type { Pattern } from '../types'

function items(
  patternId: string,
  pairs: [korean: string, japanese: string, chunkKorean: string, chunkJapanese: string][],
) {
  return pairs.map(([korean, japanese, chunkKorean, chunkJapanese], i) => ({
    id: `${patternId}-${i}`,
    patternId,
    korean,
    japanese,
    chunkKorean,
    chunkJapanese,
  }))
}

